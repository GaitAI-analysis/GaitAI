/**
 * Generation settings: as close to deterministic as a sampler gets.
 *
 * The answer must be reproducible and must not drift from the records, so the
 * temperature is low and the length is capped short. `max_new_tokens` at 300 is
 * about three tight paragraphs — the brief's own ceiling, and the panel is
 * 410px wide.
 */
export const GENERATION = {
  max_new_tokens: 300,
  temperature: 0.1,
  top_p: 0.9,
  repetition_penalty: 1.1,
  do_sample: true,
} as const;

export type Stage =
  | "idle"
  | "unsupported"
  | "downloading"
  | "initialising"
  | "ready"
  | "failed";

export interface ModelStatus {
  stage: Stage;
  /** 0–1 across the whole download, or null before the first report. */
  progress: number | null;
  /** What the visitor is told. Never a stack trace. */
  detail: string;
  device: "webgpu" | "wasm" | null;
}

/**
 * Is WebGPU actually usable?
 *
 * `'gpu' in navigator` is necessary and not sufficient — the adapter request
 * is what fails on a blocklisted driver, in a VM, or under a policy that
 * exposes the API and refuses adapters. So we ask for one.
 */
export async function detectWebGPU(): Promise<boolean> {
  try {
    const gpu = (navigator as Navigator & { gpu?: { requestAdapter(): Promise<unknown> } })
      .gpu;
    if (!gpu) return false;
    const adapter = await gpu.requestAdapter();
    return Boolean(adapter);
  } catch {
    return false;
  }
}

type Generator = (
  messages: { role: string; content: string }[],
  options: Record<string, unknown>,
) => Promise<Array<{ generated_text: unknown }>>;

let pipe: Generator | null = null;
let loading: Promise<Generator> | null = null;
let loadedId: ModelId | null = null;

export const modelReady = () => pipe !== null;
export const loadedModel = () => loadedId;

/**
 * Fetch and initialise the model. Idempotent, and safe to call again after a
 * failure — a failed attempt clears itself so a retry is a real retry.
 *
 * Progress is reported per file and aggregated: Transformers.js emits one
 * `progress` event stream per asset (weights, tokenizer, config), and reporting
 * the raw stream would show the bar restarting several times.
 */
export async function loadModel(
  id: ModelId,
  onStatus: (status: ModelStatus) => void,
): Promise<Generator> {
  if (pipe && loadedId === id) return pipe;
  if (loading) return loading;

  loading = (async () => {
    const webgpu = await detectWebGPU();
    const device: "webgpu" | "wasm" = webgpu ? "webgpu" : "wasm";

    onStatus({
      stage: "downloading",
      progress: null,
      detail: webgpu
        ? "Downloading the local language model"
        : "Downloading the local language model (CPU — no WebGPU on this browser)",
      device,
    });

    const { pipeline } = await loadRuntime();

    const seen = new Map<string, { loaded: number; total: number }>();

    const created = (await pipeline("text-generation", id, {
      /* q4f16 on WebGPU; q4 on WASM, where fp16 is not a win and is often
         unsupported. */
      dtype: webgpu ? "q4f16" : "q4",
      device,
      progress_callback: (report: unknown) => {
        const event = report as {
          status?: string;
          file?: string;
          loaded?: number;
          total?: number;
        };

        if (event.status === "progress" && event.file && event.total) {
          seen.set(event.file, {
            loaded: event.loaded ?? 0,
            total: event.total,
          });

          let loadedBytes = 0;
          let totalBytes = 0;
          for (const entry of seen.values()) {
            loadedBytes += entry.loaded;
            totalBytes += entry.total;
          }

          onStatus({
            stage: "downloading",
            progress: totalBytes > 0 ? Math.min(loadedBytes / totalBytes, 1) : null,
            detail: "Downloading the local language model",
            device,
          });
        }

        if (event.status === "ready" || event.status === "done") {
          onStatus({
            stage: "initialising",
            progress: 1,
            detail: webgpu ? "Starting WebGPU" : "Starting the CPU runtime",
            device,
          });
        }
      },
    })) as unknown as Generator;

    pipe = created;
    loadedId = id;
    onStatus({
      stage: "ready",
      progress: 1,
      detail: webgpu ? "Ready · running on WebGPU" : "Ready · running on CPU",
      device,
    });
    return created;
  })();

  try {
    return await loading;
  } catch (error) {
    pipe = null;
    loadedId = null;
    onStatus({
      stage: "failed",
      progress: null,
      /* Deliberately not the exception: the visitor is told what it means for
         them, and the assistant keeps working without it. */
      detail: "The local model could not be loaded. Answering from records.",
      device: null,
    });
    throw error;
  } finally {
    loading = null;
  }
}

/**
 * One grounded completion.
 *
 * The prompt is built by `prompt.ts` from retrieved records only, so this
 * function never decides what the model may know.
 */
export async function generate(
  system: string,
  user: string,
  signal?: AbortSignal,
): Promise<string> {
  if (!pipe) throw new Error("model not loaded");

  const output = await pipe(
    [
      { role: "system", content: system },
      { role: "user", content: user },
    ],
    { ...GENERATION, signal },
  );

  /* Transformers.js returns the full chat transcript; the answer is the last
     assistant turn, and its shape differs between chat and plain generation. */
  const text = output?.[0]?.generated_text;
  if (Array.isArray(text)) {
    const last = text[text.length - 1] as { content?: string } | undefined;
    return (last?.content ?? "").trim();
  }
  return typeof text === "string" ? text.trim() : "";
}
