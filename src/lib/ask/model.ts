"use client";

/**
 * THE LANGUAGE LAYER — an open-weight model, in the visitor's own browser.
 * =============================================================================
 * Transformers.js (`@huggingface/transformers`, Apache-2.0) running a quantized
 * ONNX build of an Apache-2.0 instruct model on WebGPU. No inference API, no
 * API key, no Cloud Function, no per-question cost, and no question leaving the
 * tab.
 *
 * THE NUMBER THAT DECIDES THE DESIGN
 * Measured from the Hugging Face CDN, `q4f16` weights:
 *
 *   onnx-community/Qwen2.5-1.5B-Instruct     1 221 878 940 B  ≈ 1.14 GiB
 *   HuggingFaceTB/SmolLM2-1.7B-Instruct      1 108 730 338 B  ≈ 1.03 GiB
 *
 * A gigabyte is not a lazy-load. It is a download a person has to agree to —
 * on a phone it may be their month. So the model is OPT-IN behind a stated
 * size, and `extractive.ts` answers immediately meanwhile. The brief asked for
 * the model to load when the panel opens; it also asked for elegance and for
 * the visitor never to feel stuck, and silently pulling 1.1 GiB from someone
 * who asked a one-line question is neither. The consent is one press, the size
 * is on it, and the choice is remembered.
 *
 * WHAT RUNS WHERE
 *   retrieval  →  always local, always first, the source of truth
 *   generation →  local, optional, and only ever fed retrieved records
 *
 * The model is a WRITER, not a source. It never sees the corpus beyond the
 * handful of records retrieval selected, and `prompt.ts` forbids it from
 * adding anything they do not establish.
 */

/**
 * THE RUNTIME IS LOADED FROM ITS OWN CDN, NOT BUNDLED.
 *
 * Three reasons, in order of weight:
 *
 *  1. IT CANNOT BE BUNDLED HERE. `onnxruntime-web`'s WebGPU bundle uses
 *     `import.meta`, and Next 14's Terser pass over an emitted asset rejects
 *     it outright: "'import.meta' cannot be used outside of module code".
 *     Aliasing the package's web build past webpack's conditional-export
 *     resolution gets as far as that, and no further.
 *  2. IT SHOULD NOT BE. The runtime is ~9 MB unpacked. Bundling it puts a
 *     webpack chunk on the deploy for something only a visitor who opts into
 *     the model ever executes, and re-downloads it on every unrelated deploy
 *     whose bundle hash changes.
 *  3. THE WEIGHTS ALREADY COME FROM A CDN. 1.1 GiB cannot live in a GitHub
 *     Pages repository, so the model path already fetches from
 *     huggingface.co. Adding the runtime alongside it changes the set of
 *     origins involved by nothing.
 *
 * WHAT THIS DOES AND DOES NOT MEAN FOR PRIVACY. Fetching the runtime and the
 * weights tells those CDNs that a browser asked for a model — the same thing
 * any script tag tells any CDN. The QUESTION never leaves the tab: it is
 * matched against a corpus already in memory and generated by weights already
 * in memory. That is the claim the panel makes, and it stays true.
 *
 * Pinned to an exact version on purpose: `@latest` would let a third party
 * change the code running in a visitor's browser without a deploy here.
 */
const RUNTIME_URL =
  "https://cdn.jsdelivr.net/npm/@huggingface/transformers@4.2.0/dist/transformers.min.js";

type TransformersModule = {
  pipeline: (
    task: string,
    model: string,
    options: Record<string, unknown>,
  ) => Promise<unknown>;
};

/**
 * `webpackIgnore` keeps the bundler out of it entirely — no resolution, no
 * chunk, no Terser pass. The URL is fetched by the browser at the moment the
 * visitor asks for the model and never before.
 */
async function loadRuntime(): Promise<TransformersModule> {
  return (await import(/* webpackIgnore: true */ RUNTIME_URL)) as TransformersModule;
}

